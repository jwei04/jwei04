    private void removePlanBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removePlanBTNActionPerformed
        int selectedRow = recoveryPlanTable.getSelectedRow();
        
        if (selectedRow >= 0) {
            // Get values from the selected row
            String studentID = recoveryPlanTable.getValueAt(selectedRow, 0).toString();
            String courseID = recoveryPlanTable.getValueAt(selectedRow, 1).toString();
            

            // Confirm deletion
            int confirm = JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to remove the recommendation for Student ID: " + studentID + 
                " and Course ID: " + courseID + "?",
                "Confirm Deletion",
                JOptionPane.YES_NO_OPTION
            );
            
            if (confirm == JOptionPane.YES_OPTION) {
                // Remove from file
                manager.removeRecord(filename, studentID, courseID);
                JOptionPane.showMessageDialog(this, "Recommendation removed successfully!");

                // Refresh table and clear text fields
                displayRecommendations();
                clearFields();
            }
        } else {
            JOptionPane.showMessageDialog(this, "Please select a row to remove.");
        }   
    }//GEN-LAST:event_removePlanBTNActionPerformed

    private void searchPlanBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchPlanBTNActionPerformed
        String studentID = StudentIDTXT.getText();
        String courseID = CourseIDTXT.getText();
        String component = ComponentTXT.getText();
        String recommendation = RecommendationTXT.getText();
    
        List<PlanRecommendation> results = manager.searchRecord(studentID, courseID, component, recommendation);   
        
        DefaultTableModel model = (DefaultTableModel) recoveryPlanTable.getModel();
        model.setRowCount(0);
        
        for (PlanRecommendation rec : results) {
            model.addRow(new Object[] {
                rec.getStudentID(),
                rec.getCourseID(),
                rec.getComponent(),
                rec.getRecommendation()
            });
        }
        
        if (results.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No matching records found.");
        }
    }//GEN-LAST:event_searchPlanBTNActionPerformed

