    private void updatePlanBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updatePlanBTNActionPerformed
        int selectedRow = recoveryPlanTable.getSelectedRow();
        
        if (selectedRow >= 0) {    
            String studentID = StudentIDTXT.getText();
            String courseID = CourseIDTXT.getText();
            String component = ComponentTXT.getText();
            String recText = RecommendationTXT.getText();
        
            if (studentID.isEmpty() || courseID.isEmpty() || component.isEmpty() || recText.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please fill in all fields!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            if (!validator.isValidStudent(studentID)) {
                JOptionPane.showMessageDialog(this, "Invalid Student ID! Please enter an existing student.");
                return;
            }

            if (!validator.isValidCourse(courseID)) {
                JOptionPane.showMessageDialog(this, "Invalid Course ID! Please enter an existing course.");
                return;
            }
                
            int confirm = JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to update this recommendation?",
                "Confirm Update",
                JOptionPane.YES_NO_OPTION
            );

            if (confirm == JOptionPane.YES_OPTION) {
                manager.updateRecord(filename, StudentIDTXT.getText(), CourseIDTXT.getText(), ComponentTXT.getText(), RecommendationTXT.getText());
                JOptionPane.showMessageDialog(this, "Recommendation updated successfully!");
                displayRecommendations();
                clearFields();
            }
        } else {
            JOptionPane.showMessageDialog(this, "Please select a row to update.");
        }
            
    }//GEN-LAST:event_updatePlanBTNActionPerformed

    private void addPlanBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addPlanBTNActionPerformed
        String studentID = StudentIDTXT.getText();
        String courseID = CourseIDTXT.getText();
        String component = ComponentTXT.getText();
        String recText = RecommendationTXT.getText();
        
        if (studentID.isEmpty() || courseID.isEmpty() || component.isEmpty() || recText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        if (!validator.isValidStudent(studentID)) {
            JOptionPane.showMessageDialog(this, "Invalid Student ID! Please enter an existing student.");
            return;
        }
        
        if (!validator.isValidCourse(courseID)) {
            JOptionPane.showMessageDialog(this, "Invalid Course ID! Please enter an existing course.");
            return;
        }
        
        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to add this new recommendation?",
            "Confirm Add",
            JOptionPane.YES_NO_OPTION
        );


        if (confirm == JOptionPane.YES_OPTION) {
            PlanRecommendation newRec = new PlanRecommendation(studentID, courseID, component, recText);
            manager.addRecord(filename, newRec);
            JOptionPane.showMessageDialog(this, "Recommendation added successfully!");
            displayRecommendations();
            clearFields();
        }

        //Clear input fields
        StudentIDTXT.setText("");
        CourseIDTXT.setText("");
        ComponentTXT.setText("");
        RecommendationTXT.setText("");
    }//GEN-LAST:event_addPlanBTNActionPerformed

