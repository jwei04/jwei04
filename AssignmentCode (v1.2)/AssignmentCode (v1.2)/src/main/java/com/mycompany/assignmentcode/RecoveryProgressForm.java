    private void displayProgress() {
        DefaultTableModel model = (DefaultTableModel) progressTable.getModel();
        model.setRowCount(0); // Clear existing rows

        List<RecoveryProgress> progresses = manager.loadFromFile(filename);
        for (RecoveryProgress rec : progresses) {
            model.addRow(new Object[]{
                rec.getStudentID(),
                rec.getCourseID(),
                rec.getComponent(),
                rec.getProgress(),
                rec.getRecoveryMark()
            });
        }
    }
    
    private void tableRowClicked(java.awt.event.MouseEvent evt) {
        int selectedRow = progressTable.getSelectedRow();
        if (selectedRow >= 0) {
            // Get table values
            String studentID = progressTable.getValueAt(selectedRow, 0).toString();
            String courseID = progressTable.getValueAt(selectedRow, 1).toString();
            String component = progressTable.getValueAt(selectedRow, 2).toString();
            String progress = progressTable.getValueAt(selectedRow, 3).toString();
            String recMark = progressTable.getValueAt(selectedRow, 4).toString();

            // Fill text fields
            StudentIDTXT.setText(studentID);
            CourseIDTXT.setText(courseID);
            ComponentTXT.setText(component);
            ProgressTXT.setText(progress);
            RecMarkTXT.setText(recMark);
        }
    }
    
