    private void searchProgressBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchProgressBTNActionPerformed
        String studentID = StudentIDTXT.getText();
        String courseID = CourseIDTXT.getText();
        String component = ComponentTXT.getText();
        String progress = ProgressTXT.getText();
        
        List<RecoveryProgress> results = manager.searchRecord(studentID, courseID, component, progress);   
        
        DefaultTableModel model = (DefaultTableModel) progressTable.getModel();
        model.setRowCount(0);
        
        for (RecoveryProgress rec : results) {
            model.addRow(new Object[] {
                rec.getStudentID(),
                rec.getCourseID(),
                rec.getComponent(),
                rec.getProgress(),
                rec.getRecoveryMark()
            });
        }
        
        if (results.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No matching records found.");
        }
    }//GEN-LAST:event_searchProgressBTNActionPerformed

    private void addProgressBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addProgressBTNActionPerformed
        String studentID = StudentIDTXT.getText();
        String courseID = CourseIDTXT.getText();
        String component = ComponentTXT.getText();
        String progress = ProgressTXT.getText();
        String recMark = RecMarkTXT.getText();
        
        if (studentID.isEmpty() || courseID.isEmpty() || component.isEmpty() || progress.isEmpty() || recMark.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        if (!validator.isValidStudent(studentID)) {
            JOptionPane.showMessageDialog(this, "Invalid Student ID! Please enter an existing student.");
            return;
        }
        
        if (!validator.isValidCourse(courseID)) {
            JOptionPane.showMessageDialog(this, "Invalid Course ID! Please enter an existing course.");
            return;
        }
        
        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to add this new Progress?",
            "Confirm Add",
            JOptionPane.YES_NO_OPTION
        );


        if (confirm == JOptionPane.YES_OPTION) {
            RecoveryProgress newRec = new RecoveryProgress(studentID, courseID, component, progress, recMark);
            manager.addRecord(filename, newRec);
            JOptionPane.showMessageDialog(this, "Progress added successfully!");
            displayProgress();
            clearFields();
        }

        //Clear input fields
        StudentIDTXT.setText("");
        CourseIDTXT.setText("");
        ComponentTXT.setText("");
        ProgressTXT.setText("");
        RecMarkTXT.setText("");
    }//GEN-LAST:event_addProgressBTNActionPerformed

    private void updateProgressBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateProgressBTNActionPerformed
        int selectedRow = progressTable.getSelectedRow();
        
        if (selectedRow >= 0) {    
            String studentID = StudentIDTXT.getText();
            String courseID = CourseIDTXT.getText();
            String component = ComponentTXT.getText();
            String progress = ProgressTXT.getText();
            String recMark = RecMarkTXT.getText();
        
            if (studentID.isEmpty() || courseID.isEmpty() || component.isEmpty() || progress.isEmpty() || recMark.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please fill in all fields!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            if (!validator.isValidStudent(studentID)) {
                JOptionPane.showMessageDialog(this, "Invalid Student ID! Please enter an existing student.");
                return;
            }

            if (!validator.isValidCourse(courseID)) {
                JOptionPane.showMessageDialog(this, "Invalid Course ID! Please enter an existing course.");
                return;
            }
                
            int confirm = JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to update this Progress?",
                "Confirm Update",
                JOptionPane.YES_NO_OPTION
            );

            if (confirm == JOptionPane.YES_OPTION) {
                String updateData = progress + "|" + recMark;
                manager.updateRecord(filename, StudentIDTXT.getText(), CourseIDTXT.getText(), ComponentTXT.getText(), updateData    );
                JOptionPane.showMessageDialog(this, "Progress updated successfully!");
                displayProgress();
                clearFields();
            }
        } else {
            JOptionPane.showMessageDialog(this, "Please select a row to update.");
        }
    }//GEN-LAST:event_updateProgressBTNActionPerformed

    private void removeProgressBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeProgressBTNActionPerformed
        int selectedRow = progressTable.getSelectedRow();
        
        if (selectedRow >= 0) {
            // Get values from the selected row
            String studentID = progressTable.getValueAt(selectedRow, 0).toString();
            String courseID = progressTable.getValueAt(selectedRow, 1).toString();
            

            // Confirm deletion
            int confirm = JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to remove the progress for Student ID: " + studentID + 
                " and Course ID: " + courseID + "?",
                "Confirm Deletion",
                JOptionPane.YES_NO_OPTION
            );
            
            if (confirm == JOptionPane.YES_OPTION) {
                // Remove from file
                manager.removeRecord(filename, studentID, courseID);
                JOptionPane.showMessageDialog(this, "Progress removed successfully!");

                // Refresh table and clear text fields
                displayProgress();
                clearFields();
            }
        } else {
            JOptionPane.showMessageDialog(this, "Please select a row to remove.");
        }   
    }//GEN-LAST:event_removeProgressBTNActionPerformed

